import type { ImageModelV4ProviderMetadata } from '@ai-sdk/provider';
import type { ProviderOptions } from '@ai-sdk/provider-utils';
import type { ImageModelResponseMetadata } from '../types/image-model-response-metadata';
import type { ImageModelUsage } from '../types/usage';
import type { Warning } from '../types/warning';

/**
 * Metadata about an input image or mask. Raw image data is intentionally not
 * included.
 */
export type GenerateImageInputFile =
  | {
      readonly type: 'url';
      readonly url: string;
    }
  | {
      readonly type: 'file';
      readonly mediaType: string;
      readonly byteLength: number;
    };

/**
 * Metadata about a generated image. Raw image data is intentionally not
 * included.
 */
export type GenerateImageOutputFile = {
  readonly mediaType: string;
  readonly byteLength: number;
};

/**
 * Event passed to telemetry integrations when image generation begins.
 */
export type GenerateImageStartEvent = {
  /** Unique identifier for this image generation call. */
  readonly callId: string;

  /** Identifies the operation type (`ai.generateImage`). */
  readonly operationId: 'ai.generateImage';

  /** The provider identifier. */
  readonly provider: string;

  /** The specific model identifier. */
  readonly modelId: string;

  /** The text prompt, when provided. */
  readonly prompt: string | undefined;

  /** Metadata about the input images, when provided. */
  readonly images: Array<GenerateImageInputFile> | undefined;

  /** Metadata about the input mask, when provided. */
  readonly mask: GenerateImageInputFile | undefined;

  /** Number of images requested. */
  readonly n: number;

  /** Maximum number of images requested per model call, when specified. */
  readonly maxImagesPerCall: number | undefined;

  /** The requested image size. */
  readonly size: `${number}x${number}` | undefined;

  /** The requested aspect ratio. */
  readonly aspectRatio: `${number}:${number}` | undefined;

  /** The requested seed. */
  readonly seed: number | undefined;

  /** Maximum number of retries for failed requests. */
  readonly maxRetries: number;

  /** Additional HTTP headers sent with the request. */
  readonly headers: Record<string, string> | undefined;

  /** Additional provider-specific options. */
  readonly providerOptions: ProviderOptions | undefined;
};

/**
 * Event passed to telemetry integrations when image generation completes.
 *
 * Raw images are intentionally not included. Integrations receive only their
 * size and media type.
 */
export type GenerateImageEndEvent = {
  /** Unique identifier for this image generation call. */
  readonly callId: string;

  /** Identifies the operation type (`ai.generateImage`). */
  readonly operationId: 'ai.generateImage';

  /** The provider identifier. */
  readonly provider: string;

  /** The specific model identifier. */
  readonly modelId: string;

  /** Metadata about the generated images. */
  readonly images: Array<GenerateImageOutputFile>;

  /** Combined usage across all image model calls. */
  readonly usage: ImageModelUsage;

  /** Warnings from all image model calls. */
  readonly warnings: Array<Warning>;

  /** Combined provider-specific metadata across all image model calls. */
  readonly providerMetadata: ImageModelV4ProviderMetadata;

  /** Response metadata from each image model call. */
  readonly responses: Array<ImageModelResponseMetadata>;
};

/**
 * Event fired when an individual image model call (doGenerate) begins.
 *
 * A `generateImage` call can make multiple image model calls when more images
 * are requested than the model supports per call, and each retry attempt is a
 * separate image model call.
 */
export type ImageModelCallStartEvent = {
  /** Unique identifier for this image generation call, used to correlate events. */
  readonly callId: string;

  /** Unique identifier for this image model call, used to correlate start and end events of parallel calls. */
  readonly imageCallId: string;

  /** Identifies the inner operation (`ai.generateImage.doGenerate`). */
  readonly operationId: 'ai.generateImage.doGenerate';

  /** The provider identifier. */
  readonly provider: string;

  /** The specific model identifier. */
  readonly modelId: string;

  /** Number of images requested in this model call. */
  readonly n: number;
};

/**
 * Event fired when an individual image model call (doGenerate) completes.
 */
export type ImageModelCallEndEvent = ImageModelCallStartEvent & {
  /** Metadata about the images generated by this model call. */
  readonly images: Array<GenerateImageOutputFile>;

  /** Usage reported by the provider for this model call, when available. */
  readonly usage: ImageModelUsage | undefined;

  /** Warnings from this model call. */
  readonly warnings: Array<Warning>;

  /** Provider-specific metadata from this model call. */
  readonly providerMetadata: ImageModelV4ProviderMetadata | undefined;

  /** Response metadata from this model call. */
  readonly response: ImageModelResponseMetadata;
};

/**
 * Event fired when an individual image model call (doGenerate) fails before it
 * returns a result. `onImageModelCallEnd` is not called for such a call.
 */
export type ImageModelCallErrorEvent = ImageModelCallStartEvent & {
  /** The error that ended the model call. */
  readonly error: unknown;
};
