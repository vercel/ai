describe.each<Mode>(['generate', 'stream'])(
  '%s workflow agent toolApproval configuration',
  mode => {
    const configurations: Array<
      [string, ToolApprovalConfiguration<ToolSet, Context>]
    > = [
      ['a per-tool status', { action: 'user-approval' }],
      ['a per-tool function', { action: () => 'user-approval' }],
      ['a generic function', () => 'user-approval'],
    ];

    it.each(configurations)(
      'requests approval for a tool without needsApproval using %s',
      async (_label, toolApproval) => {
        const execute = vi.fn(async () => 'executed');
        const options = { tools: actionTools(execute), toolApproval };

        const core = await runCore(mode, [actionResponse()], options, prompt);
        expect(execute).not.toHaveBeenCalled();
        execute.mockClear();
        const workflow = await runWorkflow(
          mode,
          [actionResponse()],
          options,
          prompt,
        );
        expect(execute).not.toHaveBeenCalled();

        for (const { run, model } of [core, workflow]) {
          expect(modelCallCount(mode, model)).toBe(1);
          expect(run.steps).toHaveLength(1);
          expect(approvalRequests(run)).toMatchObject([
            {
              approvalId: expect.any(String),
              toolCall: { toolCallId: 'call-1' },
            },
          ]);
        }
        expectSameGeneratedMessages(core.run, workflow.run);
      },
    );

    it('runs an approved call and continues like ToolLoopAgent', async () => {
      const execute = vi.fn(async () => 'executed');
      const options: AgentOptions = {
        tools: actionTools(execute),
        toolApproval: { action: 'user-approval' },
      };

      const issuedCore = await runCore(
        mode,
        [actionResponse()],
        options,
        prompt,
      );
      execute.mockClear();
      const issuedWorkflow = await runWorkflow(
        mode,
        [actionResponse()],
        options,
        prompt,
      );
      expectSameGeneratedMessages(issuedCore.run, issuedWorkflow.run);

      const resumedCore = await runCore(
        mode,
        [textResponse('Done.')],
        options,
        [
          ...prompt,
          ...issuedCore.run.messages,
          approvalResponse(
            approvalRequests(issuedCore.run)[0].approvalId,
            true,
          ),
        ],
      );
      expect(execute).toHaveBeenCalledTimes(1);
      execute.mockClear();
      const resumedWorkflow = await runWorkflow(
        mode,
        [textResponse('Done.')],
        options,
        [
          ...prompt,
          ...issuedWorkflow.run.messages,
          approvalResponse(
            approvalRequests(issuedWorkflow.run)[0].approvalId,
            true,
          ),
        ],
      );
      expect(execute).toHaveBeenCalledTimes(1);

      expectSameGeneratedMessages(resumedCore.run, resumedWorkflow.run);
      expect(JSON.stringify(resumedWorkflow.run.messages)).toContain(
        '"executed"',
      );
    });

    it('does not run a denied call', async () => {
      const execute = vi.fn(async () => 'executed');
      const options: AgentOptions = {
        tools: actionTools(execute),
        toolApproval: { action: 'user-approval' },
      };

      const issuedCore = await runCore(
        mode,
        [actionResponse()],
        options,
        prompt,
      );
      const issuedWorkflow = await runWorkflow(
        mode,
        [actionResponse()],
        options,
        prompt,
      );

      const resumedCore = await runCore(
        mode,
        [textResponse('Done.')],
        options,
        [
          ...prompt,
          ...issuedCore.run.messages,
          approvalResponse(
            approvalRequests(issuedCore.run)[0].approvalId,
            false,
          ),
        ],
      );
      execute.mockClear();
      const resumedWorkflow = await runWorkflow(
        mode,
        [textResponse('Done.')],
        options,
        [
          ...prompt,
          ...issuedWorkflow.run.messages,
          approvalResponse(
            approvalRequests(issuedWorkflow.run)[0].approvalId,
            false,
          ),
        ],
      );

      expect(execute).not.toHaveBeenCalled();
      expectSameGeneratedMessages(resumedCore.run, resumedWorkflow.run);
      expect(JSON.stringify(resumedWorkflow.run.messages)).not.toContain(
        '"executed"',
      );
    });

    it('applies the configuration over needsApproval: true', async () => {
      const execute = vi.fn(async () => 'executed');
      const options: AgentOptions = {
        tools: actionTools(execute, true),
        toolApproval: { action: 'not-applicable' },
      };

      const core = await runCore(
        mode,
        [actionResponse(), textResponse('Done.')],
        options,
        prompt,
      );
      expect(execute).toHaveBeenCalledTimes(1);
      execute.mockClear();
      const workflow = await runWorkflow(
        mode,
        [actionResponse(), textResponse('Done.')],
        options,
        prompt,
      );
      expect(execute).toHaveBeenCalledTimes(1);

      for (const { run, model } of [core, workflow]) {
        expect(modelCallCount(mode, model)).toBe(2);
        expect(approvalRequests(run)).toEqual([]);
      }
      expectSameGeneratedMessages(core.run, workflow.run);
    });

    it('keeps needsApproval for tools without a configuration entry', async () => {
      const execute = vi.fn(async () => 'executed');
      const options: AgentOptions = {
        tools: {
          ...actionTools(execute, true),
          other: tool({ inputSchema: z.object({ value: z.string() }) }),
        },
        toolApproval: { other: 'not-applicable' },
      };

      const core = await runCore(mode, [actionResponse()], options, prompt);
      expect(execute).not.toHaveBeenCalled();
      const workflow = await runWorkflow(
        mode,
        [actionResponse()],
        options,
        prompt,
      );
      expect(execute).not.toHaveBeenCalled();

      for (const { run, model } of [core, workflow]) {
        expect(modelCallCount(mode, model)).toBe(1);
        expect(approvalRequests(run)).toMatchObject([
          { toolCall: { toolCallId: 'call-1' } },
        ]);
      }
      expectSameGeneratedMessages(core.run, workflow.run);
    });

    it('lets a per-call configuration override the constructor value', async () => {
      const execute = vi.fn(async () => 'executed');
      const tools = actionTools(execute, true);

      const requestsApproval = await runWorkflow(
        mode,
        [actionResponse()],
        { tools, toolApproval: { action: 'not-applicable' } },
        prompt,
        { toolApproval: { action: 'user-approval' } },
      );
      expect(execute).not.toHaveBeenCalled();
      expect(modelCallCount(mode, requestsApproval.model)).toBe(1);
      expect(approvalRequests(requestsApproval.run)).toMatchObject([
        { toolCall: { toolCallId: 'call-1' } },
      ]);

      const runsWithoutApproval = await runWorkflow(
        mode,
        [actionResponse(), textResponse('Done.')],
        { tools, toolApproval: { action: 'user-approval' } },
        prompt,
        { toolApproval: { action: 'not-applicable' } },
      );
      expect(execute).toHaveBeenCalledTimes(1);
      expect(modelCallCount(mode, runsWithoutApproval.model)).toBe(2);
      expect(approvalRequests(runsWithoutApproval.run)).toEqual([]);
    });

    it('signs configuration approval requests and rejects tampered responses', async () => {
      vi.stubEnv('WORKFLOW_TOOL_APPROVAL_SECRET', secret);
      const execute = vi.fn(async () => 'executed');
      const model = createAgentModel([actionResponse()]);
      const agent = new WorkflowAgent({
        model,
        tools: actionTools(execute),
        toolApproval: { action: 'user-approval' },
        experimental_toolApprovalSecret: secretReference,
      });

      const issued = await agent.generate({ messages: prompt });
      const messages = issued.steps.flatMap(step => step.response.messages);
      const request = approvalRequests({ steps: issued.steps, messages })[0];
      expect(request).toMatchObject({
        approvalId: 'approval-call-1',
        signature: expect.any(String),
      });
      expect(execute).not.toHaveBeenCalled();
      expect(
        await verifyToolApprovalSignature({
          secret,
          signature: request.signature!,
          approvalId: request.approvalId,
          toolCallId: 'call-1',
          toolName: 'action',
          input: { value: 'requested' },
        }),
      ).toBe(true);

      const tampered = messages.map(message =>
        message.role === 'assistant' && Array.isArray(message.content)
          ? {
              ...message,
              content: message.content.map(part =>
                part.type === 'tool-call'
                  ? { ...part, input: { value: 'tampered' } }
                  : part,
              ),
            }
          : message,
      );
      await new WorkflowAgent({
        model: createAgentModel([textResponse('Done.')]),
        tools: actionTools(execute),
        toolApproval: { action: 'user-approval' },
        experimental_toolApprovalSecret: secretReference,
      }).generate({
        messages: [
          ...prompt,
          ...tampered,
          approvalResponse('approval-call-1', true),
        ],
      });

      expect(execute).not.toHaveBeenCalled();
    });
  },
);

describe.each<Mode>(['generate', 'stream'])(
  '%s workflow agent automatic approval decisions',
  mode => {
    const deniedConfigurations: Array<
      [string, ToolApprovalConfiguration<ToolSet, Context>]
    > = [
      ['the denied status', { action: 'denied' }],
      [
        'the denied status with a reason',
        { action: { type: 'denied', reason: 'policy' } },
      ],
    ];

    it.each(deniedConfigurations)(
      'continues after a call denied by %s like ToolLoopAgent',
      async (_label, toolApproval) => {
        const execute = vi.fn(async () => 'executed');
        const options: AgentOptions = {
          tools: actionTools(execute),
          toolApproval,
        };
        const responses = [actionResponse(), textResponse('Done.')];

        const core = await runCore(mode, responses, options, prompt);
        expect(execute).not.toHaveBeenCalled();
        expect(modelCallCount(mode, core.model)).toBe(2);
        execute.mockClear();

        const workflow = await runWorkflow(mode, responses, options, prompt);
        expect(execute).not.toHaveBeenCalled();
        expect(modelCallCount(mode, workflow.model)).toBe(2);

        expect(contentPartTypes(workflow.run)).toEqual(
          contentPartTypes(core.run),
        );
        expect(toolMessagesOfSecondCall(mode, workflow.model)).toEqual(
          toolMessagesOfSecondCall(mode, core.model),
        );
      },
    );

    it('runs a call approved by the configuration without pausing', async () => {
      const execute = vi.fn(async () => 'executed');
      const options: AgentOptions = {
        tools: actionTools(execute),
        toolApproval: { action: 'approved' },
      };
      const responses = [actionResponse(), textResponse('Done.')];

      const core = await runCore(mode, responses, options, prompt);
      expect(execute).toHaveBeenCalledTimes(1);
      expect(modelCallCount(mode, core.model)).toBe(2);
      execute.mockClear();

      const workflow = await runWorkflow(mode, responses, options, prompt);
      expect(execute).toHaveBeenCalledTimes(1);
      expect(modelCallCount(mode, workflow.model)).toBe(2);

      expect(contentPartTypes(workflow.run)).toEqual(
        contentPartTypes(core.run),
      );
      expect(toolMessagesOfSecondCall(mode, workflow.model)).toEqual(
        toolMessagesOfSecondCall(mode, core.model),
      );
    });

    function threeActionResponse(): LanguageModelV4GenerateResult {
      return {
        content: [
          { type: 'text', text: 'Checking the actions.' },
          {
            type: 'tool-call',
            toolCallId: 'call-denied',
            toolName: 'deniedAction',
            input: '{"value":"denied"}',
          },
          {
            type: 'tool-call',
            toolCallId: 'call-asked',
            toolName: 'askedAction',
            input: '{"value":"asked"}',
          },
          {
            type: 'tool-call',
            toolCallId: 'call-plain',
            toolName: 'plainAction',
            input: '{"value":"plain"}',
          },
        ],
        finishReason: { unified: 'tool-calls', raw: 'tool-calls' },
        usage,
        warnings: [],
      };
    }

    it('denies, asks, and runs calls in one step like ToolLoopAgent', async () => {
      const deniedExecute = vi.fn(async () => 'denied ran');
      const askedExecute = vi.fn(async () => 'asked ran');
      const plainExecute = vi.fn(async () => 'plain ran');
      const schema = z.object({ value: z.string() });
      const options: AgentOptions = {
        tools: {
          deniedAction: tool({ inputSchema: schema, execute: deniedExecute }),
          askedAction: tool({ inputSchema: schema, execute: askedExecute }),
          plainAction: tool({ inputSchema: schema, execute: plainExecute }),
        },
        toolApproval: { deniedAction: 'denied', askedAction: 'user-approval' },
      };
      const executedTools = () => ({
        denied: deniedExecute.mock.calls.length,
        asked: askedExecute.mock.calls.length,
        plain: plainExecute.mock.calls.length,
      });
      const responses = [threeActionResponse()];

      const core = await runCore(mode, responses, options, prompt);
      const coreExecuted = executedTools();
      for (const execute of [deniedExecute, askedExecute, plainExecute]) {
        execute.mockClear();
      }

      const workflow = await runWorkflow(mode, responses, options, prompt);

      expect(coreExecuted).toEqual({ denied: 0, asked: 0, plain: 1 });
      expect(executedTools()).toEqual(coreExecuted);
      expect(sortedContentPartTypes(workflow.run)).toEqual(
        sortedContentPartTypes(core.run),
      );
      for (const { run, model } of [core, workflow]) {
        expect(modelCallCount(mode, model)).toBe(1);
        expect(
          approvalRequests(run).map(request => ({
            toolCallId: request.toolCall.toolCallId,
            isAutomatic: request.isAutomatic,
          })),
        ).toEqual([
          { toolCallId: 'call-denied', isAutomatic: true },
          { toolCallId: 'call-asked', isAutomatic: undefined },
        ]);
      }
    });
  },
);

describe('stream workflow agent automatic approval decisions', () => {
  it('writes a denied tool output and no approval request for a denied call', async () => {
    const chunks: Array<{ type: string; toolCallId?: string }> = [];
    const execute = vi.fn(async () => 'executed');
    const model = createAgentModel([actionResponse(), textResponse('Done.')]);
    const agent = new WorkflowAgent({
      model,
      tools: actionTools(execute),
      toolApproval: { action: 'denied' },
    });

    const result = await agent.stream({
      messages: prompt,
      writable: new WritableStream({
        write(chunk) {
          chunks.push(chunk as { type: string; toolCallId?: string });
        },
      }),
    });

    expect(result.steps).toHaveLength(2);
    expect(execute).not.toHaveBeenCalled();
    expect(chunks).toContainEqual({
      type: 'tool-output-denied',
      toolCallId: 'call-1',
    });
    expect(
      chunks.filter(
        chunk =>
          chunk.type === 'tool-approval-request' &&
          chunk.toolCallId === 'call-1',
      ),
    ).toEqual([]);
  });
});

/**
 * The same scripted responses for core generate and Workflow stream tests.
 * Deliberately supports only the content used by these fixtures, so adding a
 * new content kind requires defining its equivalent streaming representation.
 */
function createAgentModel(responses: LanguageModelV4GenerateResult[]) {
  return new MockLanguageModelV4({
    doGenerate: responses,
    doStream: responses.map(response => {
      const parts: LanguageModelV4StreamPart[] = [
        { type: 'stream-start', warnings: response.warnings },
      ];

      for (const part of response.content) {
        switch (part.type) {
          case 'text': {
            parts.push(
              { type: 'text-start', id: 'text' },
              { type: 'text-delta', id: 'text', delta: part.text },
              { type: 'text-end', id: 'text' },
            );
            break;
          }
          case 'tool-call':
            parts.push(part);
            break;
          default:
            throw new Error(`Unsupported fixture content: ${part.type}`);
        }
      }

      parts.push({
        type: 'finish',
        finishReason: response.finishReason,
        usage: response.usage,
      });

      return { stream: convertArrayToReadableStream(parts) };
    }),
  });
}
