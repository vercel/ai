type Mode = 'generate' | 'stream';

const prompt: ModelMessage[] = [
  { role: 'user', content: 'Perform the action.' },
];

const secret = 'tool-approval-config-secret';
const secretReference = {
  environmentVariable: 'WORKFLOW_TOOL_APPROVAL_SECRET',
};

const usage = {
  inputTokens: {
    total: 2,
    noCache: 2,
    cacheRead: undefined,
    cacheWrite: undefined,
  },
  outputTokens: { total: 1, text: 1, reasoning: undefined },
};

function actionResponse(): LanguageModelV4GenerateResult {
  return {
    content: [
      { type: 'text', text: 'Checking the action.' },
      {
        type: 'tool-call',
        toolCallId: 'call-1',
        toolName: 'action',
        input: '{"value":"requested"}',
      },
    ],
    finishReason: { unified: 'tool-calls', raw: 'tool-calls' },
    usage,
    warnings: [],
  };
}

function textResponse(text: string): LanguageModelV4GenerateResult {
  return {
    content: [{ type: 'text', text }],
    finishReason: { unified: 'stop', raw: 'stop' },
    usage,
    warnings: [],
  };
}

function actionTools(
  execute: () => Promise<string>,
  needsApproval?: boolean,
): ToolSet {
  return {
    action: tool({
      inputSchema: z.object({ value: z.string() }),
      ...(needsApproval == null ? {} : { needsApproval }),
      execute,
    }),
  };
}

type AgentOptions = {
  tools: ToolSet;
  toolApproval?: ToolApprovalConfiguration<ToolSet, Context>;
};

type CallOptions = {
  toolApproval?: ToolApprovalConfiguration<ToolSet, Context>;
};

type AgentRun = {
  steps: Array<StepResult<ToolSet>>;
  messages: Array<ModelMessage>;
};

async function runCore(
  mode: Mode,
  responses: LanguageModelV4GenerateResult[],
  options: AgentOptions,
  messages: ModelMessage[],
  callOptions: CallOptions = {},
): Promise<{ run: AgentRun; model: MockLanguageModelV4 }> {
  const model = createAgentModel(responses);
  const agent = new ToolLoopAgent({ ...options, model });
  if (mode === 'generate') {
    const result = await agent.generate({ messages, ...callOptions });
    return {
      run: { steps: result.steps, messages: result.responseMessages },
      model,
    };
  }
  const result = await agent.stream({ messages, ...callOptions });
  await result.consumeStream();
  return {
    run: {
      steps: await result.steps,
      messages: await result.responseMessages,
    },
    model,
  };
}

async function runWorkflow(
  mode: Mode,
  responses: LanguageModelV4GenerateResult[],
  options: AgentOptions,
  messages: ModelMessage[],
  callOptions: CallOptions = {},
): Promise<{ run: AgentRun; model: MockLanguageModelV4 }> {
  const model = createAgentModel(responses);
  const agent = new WorkflowAgent({ ...options, model });
  if (mode === 'generate') {
    const result = await agent.generate({ messages, ...callOptions });
    return {
      run: { steps: result.steps, messages: result.responseMessages },
      model,
    };
  }
  const result = await agent.stream({ messages, ...callOptions });
  return {
    run: { steps: result.steps, messages: result.messages },
    model,
  };
}

function modelCallCount(mode: Mode, model: MockLanguageModelV4): number {
  return mode === 'generate'
    ? model.doGenerateCalls.length
    : model.doStreamCalls.length;
}

function approvalRequests(run: AgentRun) {
  return run.steps
    .flatMap(step => step.content)
    .filter(part => part.type === 'tool-approval-request') as Array<{
    type: 'tool-approval-request';
    approvalId: string;
    toolCall: { toolCallId: string };
    isAutomatic?: boolean;
    signature?: string;
  }>;
}

/**
 * Approval ids are generated per agent, so normalize them before comparing.
 * Core reports only the messages generated by the call, so WorkflowAgent
 * conversations are compared on the same generated tail.
 */
function comparable(run: AgentRun, limit?: number) {
  const messages =
    limit == null
      ? run.messages
      : run.messages.slice(Math.max(0, run.messages.length - limit));
  let text = JSON.stringify(messages);
  for (const [index, request] of approvalRequests(run).entries()) {
    text = text.split(request.approvalId).join(`approval-${index}`);
  }
  return JSON.parse(text);
}

function expectSameGeneratedMessages(core: AgentRun, workflow: AgentRun) {
  expect(comparable(workflow, core.messages.length)).toEqual(comparable(core));
}

function contentPartTypes(run: AgentRun): string[][] {
  return run.steps.map(step => step.content.map(part => part.type));
}

/**
 * `streamText` emits approval parts inline with the tool calls, while
 * `generateText` emits them after the tool results. The comparison of a step
 * with several tool calls therefore ignores the order of the parts.
 */
function sortedContentPartTypes(run: AgentRun): string[][] {
  return contentPartTypes(run).map(types => [...types].sort());
}

function toolMessagesOfSecondCall(mode: Mode, model: MockLanguageModelV4) {
  const calls =
    mode === 'generate' ? model.doGenerateCalls : model.doStreamCalls;
  return calls[1].prompt.filter(message => message.role === 'tool');
}

function approvalResponse(approvalId: string, approved: boolean): ModelMessage {
  return {
    role: 'tool',
    content: [{ type: 'tool-approval-response', approvalId, approved }],
  };
}

