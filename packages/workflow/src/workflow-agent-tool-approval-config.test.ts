import {
  ToolLoopAgent,
  tool,
  type ModelMessage,
  type StepResult,
  type ToolApprovalConfiguration,
  type ToolSet,
} from 'ai';
import { verifyToolApprovalSignature } from 'ai/internal';
import { MockLanguageModelV4, convertArrayToReadableStream } from 'ai/test';
