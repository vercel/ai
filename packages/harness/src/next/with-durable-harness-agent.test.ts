import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, test, vi } from 'vitest';
import {
  withDurableHarnessAgent,
  writeQueueHandlerRoute,
} from './with-durable-harness-agent';

const agentCode = `import { HarnessAgent } from '@ai-sdk/harness/agent';
export const agent = new HarnessAgent({ id: 'a' });`;

function createProject(options: { appDir?: string } = {}): string {
  const projectDir = mkdtempSync(join(tmpdir(), 'harness-next-'));
  mkdirSync(join(projectDir, options.appDir ?? 'app'), { recursive: true });
  mkdirSync(join(projectDir, 'agent/pi'), { recursive: true });
  writeFileSync(join(projectDir, 'agent/pi/basic.ts'), agentCode);
  return projectDir;
}

const routeFile = (projectDir: string, appDir = 'app') =>
  join(projectDir, appDir, '.well-known/harness-agent/v1/flow/route.js');

describe('writeQueueHandlerRoute', () => {
  test('writes the route that imports the agent modules', () => {
    const projectDir = createProject();

    writeQueueHandlerRoute({ projectDir });

    expect(readFileSync(routeFile(projectDir), 'utf8')).toMatchInlineSnapshot(`
      "// generated by @ai-sdk/harness/next. Do not edit: it is written again on every build and dev server start.
      import '../../../../../agent/pi/basic';
      import { createDurableHarnessAgentQueueHandler } from '@ai-sdk/harness/agent';

      export const POST = createDurableHarnessAgentQueueHandler();
      "
    `);
    expect(
      readFileSync(
        join(projectDir, 'app/.well-known/harness-agent/.gitignore'),
        'utf8',
      ),
    ).toBe('# generated by @ai-sdk/harness/next\n*\n');
  });

  test('writes the route into src/app', () => {
    const projectDir = createProject({ appDir: 'src/app' });

    writeQueueHandlerRoute({ projectDir });

    expect(readFileSync(routeFile(projectDir, 'src/app'), 'utf8')).toContain(
      `import '../../../../../../agent/pi/basic';`,
    );
  });

  test('imports the given agent modules instead of the detected ones', () => {
    const projectDir = createProject();
    mkdirSync(join(projectDir, 'lib'));
    writeFileSync(join(projectDir, 'lib/agents.ts'), 'export {};');

    writeQueueHandlerRoute({ projectDir, agents: ['lib/agents.ts'] });

    const route = readFileSync(routeFile(projectDir), 'utf8');
    expect(route).toContain(`import '../../../../../lib/agents';`);
    expect(route).not.toContain('agent/pi/basic');
  });

  test('leaves the app its own route', () => {
    const projectDir = createProject();
    const ownRoute = join(
      projectDir,
      'app/.well-known/harness-agent/v1/flow/route.ts',
    );
    mkdirSync(join(ownRoute, '..'), { recursive: true });
    writeFileSync(ownRoute, 'export const POST = () => {};');

    writeQueueHandlerRoute({ projectDir });

    expect(existsSync(routeFile(projectDir))).toBe(false);
    expect(readFileSync(ownRoute, 'utf8')).toBe(
      'export const POST = () => {};',
    );
  });

  test('writes nothing without an app directory', () => {
    const projectDir = mkdtempSync(join(tmpdir(), 'harness-next-'));
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
    try {
      writeQueueHandlerRoute({ projectDir });
    } finally {
      warn.mockRestore();
    }

    expect(existsSync(join(projectDir, 'app'))).toBe(false);
  });
});

describe('withDurableHarnessAgent', () => {
  test('returns the config, resolved from a function', async () => {
    const config = withDurableHarnessAgent(async () => ({
      reactStrictMode: true,
    }));

    expect(
      await config('phase-production-server', { defaultConfig: {} }),
    ).toEqual({ reactStrictMode: true });
  });
});
