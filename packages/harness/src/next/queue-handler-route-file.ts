import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { getDurableHarnessAgentQueueHandlerRoute } from '../agent/v2/internal/durable-agent-queue';

/**
 * Marker in the first line of a queue handler route that
 * `withDurableHarnessAgent` writes. A route file without it is the app's
 * own, and is left alone.
 */
export const QUEUE_HANDLER_ROUTE_MARKER = 'generated by @ai-sdk/harness/next';

/**
 * Extensions of the route files Next.js recognizes.
 */
const ROUTE_FILE_EXTENSIONS = ['js', 'ts', 'mjs', 'mts', 'jsx', 'tsx'];

/**
 * The Next.js app directory of the project: `app`, or `src/app`. Undefined
 * if the project has neither.
 */
export function findNextAppDir(options: {
  projectDir: string;
}): string | undefined {
  for (const dir of ['app', join('src', 'app')]) {
    const appDir = join(options.projectDir, dir);
    if (existsSync(appDir) && statSync(appDir).isDirectory()) return appDir;
  }
  return undefined;
}

/**
 * Directory of the queue handler route in the app directory: the route's
 * path from `getDurableHarnessAgentQueueHandlerRoute()` under `<app>`, by
 * default `<app>/.well-known/harness-agent/v1/flow`.
 */
export function getQueueHandlerRouteDir(options: { appDir: string }): string {
  return join(
    options.appDir,
    ...getDurableHarnessAgentQueueHandlerRoute().split('/').filter(Boolean),
  );
}

/**
 * The app's own route file at the queue handler route's path, if it has
 * one: a route file without `QUEUE_HANDLER_ROUTE_MARKER`.
 */
export function findOwnQueueHandlerRouteFile(options: {
  appDir: string;
}): string | undefined {
  const routeDir = getQueueHandlerRouteDir(options);
  return ROUTE_FILE_EXTENSIONS.map(extension =>
    join(routeDir, `route.${extension}`),
  ).find(
    file =>
      existsSync(file) &&
      !readFileSync(file, 'utf8').includes(QUEUE_HANDLER_ROUTE_MARKER),
  );
}
